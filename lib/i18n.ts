export function translate(lang: Lang, key: string, fallback?: string): string {
  return DICT[lang]?.[key] ?? DICT.en[key] ?? fallback ?? key;
}

export function useT(): (key: string, fallback?: string) => string {
  const [session] = useSessionRaw();
  const lang = session.lang;
  return (key: string, fallback?: string) => translate(lang, key, fallback);
}

function useSessionRaw(): [Session, (next: Session | ((prev: Session) => Session)) => void] {
  return useStoredValue<Session>(KEYS.session, { userId: null, lang: "en" });
}

export function useLang(): Lang {
  const [session] = useSessionRaw();
  return session.lang;
}